"""Content intelligence pipeline orchestrating language detection, claims, entities, and signals."""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from sangyan.domain.models import Claim, ContentItem, Entity, Signal
from sangyan.intelligence.claims import ClaimExtractor
from sangyan.intelligence.entities import EntityResolver
from sangyan.intelligence.language import LanguageDetector, LanguageResult
from sangyan.intelligence.signals import SignalDetector
from sangyan.tenancy.repository import TenantRepository


@dataclass
class AnalysisResult:
    """Consolidated output of the Content Intelligence Engine."""

    content_item: ContentItem
    language: LanguageResult
    claims: list[Claim] = field(default_factory=list)
    entities: list[Entity] = field(default_factory=list)
    signals: list[Signal] = field(default_factory=list)
    risk_score: float = 0.0
    summary: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "content_item_id": self.content_item.id,
            "language": self.language.to_dict(),
            "claims_count": len(self.claims),
            "claims": [c.to_dict() for c in self.claims],
            "entities_count": len(self.entities),
            "entities": [e.to_dict() for e in self.entities],
            "signals_count": len(self.signals),
            "signals": [s.to_dict() for s in self.signals],
            "risk_score": round(self.risk_score, 4),
            "summary": self.summary,
        }


# Weights assigned to signals when computing initial content risk posture
SIGNAL_SEVERITY_WEIGHTS = {
    "OTP_REQUEST": 1.0,
    "CREDENTIAL_REQUEST": 1.0,
    "WITHDRAWAL_FEE": 0.95,
    "GUARANTEED_RETURN": 0.90,
    "HIGH_RETURN_PROMISE": 0.85,
    "AUTHORITY_IMPERSONATION": 0.85,
    "UNVERIFIED_APP": 0.85,
    "SUSPICIOUS_URL": 0.80,
    "THIRD_PARTY_PAYMENT": 0.80,
    "UPI_MISMATCH": 0.80,
    "PRESSURE_LANGUAGE": 0.70,
    "URGENCY": 0.65,
    "SCARCITY": 0.65,
    "SOCIAL_MEDIA_SOLICITATION": 0.60,
    "FAKE_PROFIT": 0.55,
}


class ContentIntelligenceEngine:
    """Orchestrates multilingual detection, claim decomposition, entity resolution, and signal detection."""

    def __init__(
        self,
        language_detector: LanguageDetector | None = None,
        claim_extractor: ClaimExtractor | None = None,
        entity_resolver: EntityResolver | None = None,
        signal_detector: SignalDetector | None = None,
    ) -> None:
        self.language_detector = language_detector or LanguageDetector()
        self.claim_extractor = claim_extractor or ClaimExtractor()
        self.entity_resolver = entity_resolver or EntityResolver()
        self.signal_detector = signal_detector or SignalDetector()

    def analyze(self, content_item: ContentItem) -> AnalysisResult:
        """Run complete intelligence analysis pipeline on a ContentItem."""
        text = content_item.normalized_text or content_item.raw_content

        # 1. Multilingual identification
        lang_res = self.language_detector.detect(text)
        content_item.language = lang_res.primary_language
        content_item.metadata["language_result"] = lang_res.to_dict()

        # 2. Decompose claims
        claims = self.claim_extractor.extract_claims(text, content_item.id)

        # 3. Resolve financial entities
        entities = self.entity_resolver.resolve_entities(text)

        # 4. Detect observable safety signals
        signals = self.signal_detector.detect_signals(text, content_item.id)

        # 5. Compute risk score based on signal weights and density
        risk_score = self._compute_risk_score(signals)

        # 6. Generate human-readable summary
        summary = self._generate_summary(lang_res, claims, entities, signals, risk_score)

        return AnalysisResult(
            content_item=content_item,
            language=lang_res,
            claims=claims,
            entities=entities,
            signals=signals,
            risk_score=risk_score,
            summary=summary,
        )

    def persist_analysis(
        self, analysis: AnalysisResult, repository: TenantRepository
    ) -> dict[str, list[str]]:
        """Persist claims, entities, and signals generated by analysis into TenantRepository."""
        saved_claim_ids: list[str] = []
        for claim in analysis.claims:
            cid = repository.save_claim(claim)
            saved_claim_ids.append(cid)

        saved_entity_ids: list[str] = []
        for entity in analysis.entities:
            eid = repository.save_entity(entity)
            saved_entity_ids.append(eid)

        saved_signal_ids: list[str] = []
        for signal in analysis.signals:
            sid = repository.save_signal(signal)
            saved_signal_ids.append(sid)

        return {
            "claim_ids": saved_claim_ids,
            "entity_ids": saved_entity_ids,
            "signal_ids": saved_signal_ids,
        }

    def _compute_risk_score(self, signals: list[Signal]) -> float:
        if not signals:
            return 0.0
        # Diminishing returns formula using weighted severity
        weights = [SIGNAL_SEVERITY_WEIGHTS.get(s.signal_type, 0.5) * s.confidence for s in signals]
        max_weight = max(weights) if weights else 0.0
        sum_remaining = sum(sorted(weights, reverse=True)[1:])
        combined = max_weight + (1.0 - max_weight) * (1.0 - (0.5 ** (sum_remaining / 0.8)))
        return round(min(combined, 1.0), 4)

    def _generate_summary(
        self,
        lang: LanguageResult,
        claims: list[Claim],
        entities: list[Entity],
        signals: list[Signal],
        risk_score: float,
    ) -> str:
        parts: list[str] = []
        parts.append(
            f"Content analyzed in language '{lang.primary_language}' (script: {lang.script})."
        )
        if signals:
            sig_types = sorted(list({s.signal_type for s in signals}))
            parts.append(
                f"Detected {len(signals)} safety signal(s) indicating potential risk (risk score: {risk_score:.2f}): {', '.join(sig_types)}."
            )
        else:
            parts.append("No predatory persuasion or high-risk safety signals were identified.")

        if claims:
            parts.append(f"Decomposed {len(claims)} atomic claim(s) requiring verification.")
        if entities:
            ent_names = [e.name for e in entities[:3]]
            parts.append(f"Identified {len(entities)} financial entity/identifier(s): {', '.join(ent_names)}.")

        return " ".join(parts)
